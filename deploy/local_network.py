"""Generate a private LAN overlay without editing source configuration."""

import ipaddress
import json
import os
import socket
import tomllib
from pathlib import Path


def load_network(path):
    if not path.exists():
        return "off"
    settings = tomllib.loads(path.read_text())
    if set(settings) - {"lan_host"}:
        raise ValueError("Unknown deployment setting; supported: lan_host")
    host = settings.get("lan_host", "off")
    if not isinstance(host, str):
        raise TypeError("lan_host must be auto, off, or a local private IPv4 address")
    return host


def write_ios_network(root, public_url):
    path = root / "apps/ios/Config/Network.generated.xcconfig"
    value = public_url.replace("://", ":/$()/")
    private_write(
        path,
        "// Generated by hymio start. Edit deploy/local.toml, not this file.\nHYMIO_BACKEND_URL = "
        + value
        + "\n",
    )


def lan_address(value):
    if not value or value == "off":
        return None
    if value == "auto":
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            sock.connect(("1.1.1.1", 80))
            value = sock.getsockname()[0]
    address = ipaddress.IPv4Address(value)
    if (
        address.is_loopback
        or address.is_unspecified
        or address.is_multicast
        or not address.is_private
    ):
        raise ValueError(
            "lan_host requires a private IPv4 address assigned to this Mac/host"
        )
    with socket.socket() as sock:
        sock.bind((str(address), 0))
    return str(address)


def private_write(path, text):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd, "w") as output:
        output.write(text)


def prepare_lan(root, config, config_path, address):
    public = f"http://{address}:8080"
    overlay = dict(config)
    for key in ("database", "client_secret_file", "service_token_file", "e2b_key_file"):
        if overlay.get(key):
            overlay[key] = str(
                (config_path.parent / Path(overlay[key]).expanduser()).resolve()
            )
    if config.get("login_method", "account") != "account":
        raise ValueError(
            "LAN auto-configuration currently requires account login; configure public OIDC callbacks for browser login"
        )
    overlay.update(public_url=public)
    overlay["origins"] = list(
        dict.fromkeys([*config["origins"], f"http://{address}:1420"])
    )
    target = config_path.with_name("hymio-lan.local.toml")
    if target.resolve() == config_path.resolve():
        raise ValueError("Use the source Backend config, not its generated LAN overlay")
    private_write(
        target,
        "\n".join(
            f"{key} = {json.dumps(value, ensure_ascii=False)}"
            for key, value in overlay.items()
        )
        + "\n",
    )
    return overlay, target
